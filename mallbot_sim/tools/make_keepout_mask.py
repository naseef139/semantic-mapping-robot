#!/usr/bin/env python3
"""
Generate the Nav2 KEEPOUT mask for mall_v2: every shop interior is a no-go zone, the robot stays
in the public corridor (it still SEES into the shops through the doorways).

The mask must be in the SLAM `map` frame. slam_toolbox puts the map origin at the robot's START
pose, so the mask depends on the spawn pose (default x=-10, y=0, yaw=0 -> map = world shifted by +10 in x).

  python3 tools/make_keepout_mask.py                    # default spawn
  python3 tools/make_keepout_mask.py --spawn -10 0 0     # x y yaw(rad) used in sim.launch.py

Writes config/keepout_mall_v2.pgm + .yaml  (black = keepout, grey = no effect; never white, see below).
On the REAL robot: draw the same kind of image over your saved map (GIMP etc.): black zones on a GREY (128) background.
"""
import argparse
import math
import os

from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
CFG = os.path.normpath(os.path.join(HERE, "..", "config"))

RES = 0.05
WORLD_X = (-12.5, 12.5)
WORLD_Y = (-7.5, 7.5)
CORRIDOR_HALF = 2.0          # front walls of the shops at y = +/-2.0
WALL_HALF = 0.075
MARGIN = 0.05                # keepout starts just inside the shop (doorway line), not in the corridor


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--spawn", type=float, nargs=3, default=[-10.0, 0.0, 0.0], metavar=("X", "Y", "YAW"))
    a = ap.parse_args()
    sx, sy, syaw = a.spawn
    c, s = math.cos(syaw), math.sin(syaw)

    def world_to_map(x, y):                       # inverse of the spawn transform
        dx, dy = x - sx, y - sy
        return c * dx + s * dy, -s * dx + c * dy

    # map-frame bounding box of the world
    corners = [world_to_map(x, y) for x in WORLD_X for y in WORLD_Y]
    mx0, my0 = min(p[0] for p in corners), min(p[1] for p in corners)
    mx1, my1 = max(p[0] for p in corners), max(p[1] for p in corners)
    w, h = int(round((mx1 - mx0) / RES)), int(round((my1 - my0) / RES))
    # GREY (unknown) everywhere except the zones. NOT white: Nav2's KeepoutFilter copies the mask into
    # every costmap cell that is still unknown (keepout_filter.cpp: `old_data == NO_INFORMATION`), so a
    # white mask would turn all unexplored space into "free" and the explorer would find no frontiers.
    # Grey -> OCC_GRID_UNKNOWN -> the filter skips those cells.
    img = Image.new("L", (w, h), 128)
    d = ImageDraw.Draw(img)

    def px(mx, my):                               # map metres -> image pixel (row 0 = top = max y)
        return ((mx - mx0) / RES, (my1 - my) / RES)

    y_in = CORRIDOR_HALF + WALL_HALF + MARGIN
    for y_a, y_b in ((y_in, WORLD_Y[1]), (WORLD_Y[0], -y_in)):    # north shops, south shops
        poly = [world_to_map(WORLD_X[0], y_a), world_to_map(WORLD_X[1], y_a),
                world_to_map(WORLD_X[1], y_b), world_to_map(WORLD_X[0], y_b)]
        d.polygon([px(*p) for p in poly], fill=0)                  # black = keepout

    pgm = os.path.join(CFG, "keepout_mall_v2.pgm")
    img.save(pgm)
    with open(os.path.join(CFG, "keepout_mall_v2.yaml"), "w") as f:
        f.write(f"# Nav2 keepout mask for mall_v2, map frame, robot spawned at world ({sx}, {sy}, yaw {syaw})\n"
                f"# black = no-go (shop interiors), grey = no effect (must not be white). Generated by tools/make_keepout_mask.py\n"
                f"image: keepout_mall_v2.pgm\nmode: trinary\nresolution: {RES}\n"
                f"origin: [{mx0:.3f}, {my0:.3f}, 0.0]\nnegate: 0\noccupied_thresh: 0.65\nfree_thresh: 0.196\n")
    print(f"keepout mask {w}x{h} px, origin ({mx0:.2f}, {my0:.2f}) in map frame -> {pgm}")


if __name__ == "__main__":
    main()
